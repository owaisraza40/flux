function crc32(bytes) {
  let crc = -1;
  for (const value of bytes) {
    crc ^= value;
    for (let bit = 0; bit < 8; bit++) crc = (crc >>> 1) ^ (0xedb88320 & -(crc & 1));
  }
  return (crc ^ -1) >>> 0;
}
function pngChunk(type, data) {
  const tag = Buffer.from(type);
  const result = Buffer.alloc(12 + data.length);
  result.writeUInt32BE(data.length, 0); tag.copy(result, 4); data.copy(result, 8);
  result.writeUInt32BE(crc32(Buffer.concat([tag, data])), 8 + data.length);
  return result;
}
function iconPng(size) {
  const pixels = Buffer.alloc((size * 4 + 1) * size);
  const foreground = [240, 238, 245, 255];
  const background = [200, 16, 46, 255];
  for (let row = 0; row < size; row++) for (let column = 0; column < size; column++) {
    const x = (column + .5) / size, y = (row + .5) / size;
    const radius = .04;
    const dx = Math.max(radius - x, 0, x - (1 - radius));
    const dy = Math.max(radius - y, 0, y - (1 - radius));
    const inside = dx * dx + dy * dy <= radius * radius;
    const shaft = x >= .445 && x <= .555 && y >= .21 && y <= .55;
    const head = y >= .43 && y <= .69 && Math.abs(x - .5) <= (.69 - y) * .9;
    const tray = x >= .24 && x <= .76 && y >= .75 && y <= .83;
    const color = !inside ? [0, 0, 0, 0] : shaft || head || tray ? foreground : background;
    const offset = row * (size * 4 + 1) + 1 + column * 4;
    for (let channel = 0; channel < 4; channel++) pixels[offset + channel] = color[channel];
  }
  const header = Buffer.alloc(13); header.writeUInt32BE(size, 0); header.writeUInt32BE(size, 4); header[8] = 8; header[9] = 6;
  return Buffer.concat([Buffer.from([137,80,78,71,13,10,26,10]), pngChunk("IHDR", header), pngChunk("IDAT", deflateSync(pixels)), pngChunk("IEND", Buffer.alloc(0))]);
}

